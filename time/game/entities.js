// World vars
export let levelIndex = 0;
export let levelRows = LEVELS[0].slice();
export let tiles = [];
export let W = 0, H = 0;
let playerSpawn = { x: 0, y: 0 };
export let goal = { x: 0, y: 0, w: 0, h: 0 };
export const enemies = [];
export const ENEMY_SIZE = TILE;
export const movers = [];

// Normalize ragged ascii
function normalize(arr) {
  const m = arr.reduce((a, r) => Math.max(a, r.length), 0) || 64;
  return arr.map(r => (r + '.'.repeat(m - r.length)).slice(0, m));
}

function ensureSpawn() {
  let found = false;
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      if (tiles[y][x] === 'S' || tiles[y][x] === 's') {
        playerSpawn = { x: x * TILE, y: y * TILE };
        found = true;
      }
    }
  }
  if (!found) {
    tiles[0][0] = 'S';
    playerSpawn = { x: 0, y: 0 };
  }
}

// Build world from ascii
export function rebuildFromRows() {
  levelRows = normalize(levelRows);
  H = levelRows.length;
  W = levelRows[0].length;
  tiles = Array.from({ length: H }, (_, y) => levelRows[y].split(''));
  enemies.length = 0;
  movers.length = 0;
  collectibles.length = 0;
  goal = { x: 0, y: 0, w: TILE, h: TILE };

  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      const t = tiles[y][x];
      if (t === 'P') tiles[y][x] = 'S';
      if (t === 'S' || t === 's') playerSpawn = { x: x * TILE, y: y * TILE };
      if (t === 'F') goal = { x: x * TILE, y: y * TILE, w: TILE, h: TILE };
      if (t === 'E') {
        enemies.push({ x: x * TILE, y: y * TILE + TILE, w: TILE, h: TILE, vy: 0, dir: 1, vx: 0.8 });
        tiles[y][x] = '.';
      }
      if (t === 'H') movers.push({ x: x * TILE, y: y * TILE, dir: 1, type: 'H' });
      if (t === 'V') movers.push({ x: x * TILE, y: y * TILE, dir: 1, type: 'V' });
      if (t === '[') {
        // moving platform
        movers.push({ x: x * TILE, y: y * TILE, dir: 1, type: 'P', speed:1.5, min:null, max:null });
        tiles[y][x] = '.';
        // fixed 5‑block patrol range
        const last = movers[movers.length - 1];
        if (last.type === 'P') {
            last.min = last.x - (5 * TILE);
            last.max = last.x + (5 * TILE);
        }
      }
      if (t === 'G') {
        collectibles.push({ x: x * TILE, y: y * TILE, w: TILE, h: TILE });
        tiles[y][x] = '.';
      }
    }
  }
  // auto‑insert a flag if level has none
  let hasFlag = false;
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    if (tiles[y][x] === 'F') hasFlag = true;
  }
  if (!hasFlag) {
    // place a flag on the last solid ground in the last row
    for (let row = H - 1; row >= 0; row--) {
      for (let col = W - 1; col >= 0; col--) {
        if (tiles[row][col] === '#') {
          tiles[row - 1][col] = 'F';
          goal = { x: col * TILE, y: (row - 1) * TILE, w: TILE, h: TILE };
          break;
        }
      }
      if (hasFlag) break;
    }
  }
  ensureSpawn();
  updateLabel();
}

export function loadLevel(i) {
  levelIndex = (i + LEVELS.length) % LEVELS.length;
  levelRows = LEVELS[levelIndex].slice();
  rebuildFromRows();
}

export function nextLevel() { loadLevel(levelIndex + 1); }
export function prevLevel() { loadLevel(levelIndex - 1); }

export function addBlankLevel() {
  const w = W || 64, h = H || 12;
  const r = Array(h).fill('.'.repeat(w));
  r[h - 1] = '#'.repeat(w);
  r[1] = 'S' + r[1].slice(1);
  r[2] = r[2].slice(0, w - 3) + 'F';
  LEVELS.splice(levelIndex + 1, 0, r);
  loadLevel(levelIndex + 1);
}

export function duplicateLevel() {
  LEVELS.splice(levelIndex + 1, 0, levelRows.slice());
  loadLevel(levelIndex + 1);
}

function updateLabel() {
  const el = document.getElementById('levelLabel');
  if (el) el.textContent = `Level ${levelIndex + 1}/${LEVELS.length}`;
}

export const player = { x: 0, y: 0, w: 28, h: 40, vx: 0, vy: 0, onGround: false, facing: 1, jumpsLeft: 2 };
export function teleportToSpawn() {
  player.x = playerSpawn.x;
  player.y = playerSpawn.y;
  player.vx = player.vy = 0;
  player.onGround = false;
  player.jumpsLeft = 2;
}

export function reset() { teleportToSpawn(); }

/*** EDITOR PAINT ***/
export function paintAtCursor(erasing = false) {
  const tx = Math.floor((mouse.x + camera.x) / TILE);
  const ty = Math.floor((mouse.y + camera.y) / TILE);
  placeTile(tx, ty, erasing ? '.' : currentBrush);
}

function placeTile(tx, ty, ch) {
  if (tx < 0 || ty < 0 || tx >= W || ty >= H) return;
  if (ch === 'S' || ch === 's') {
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
      if (tiles[y][x] === 'S' || tiles[y][x] === 's') tiles[y][x] = '.';
    }
    playerSpawn = { x: tx * TILE, y: ty * TILE };
  }
  if (ch === 'F') {
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
      if (tiles[y][x] === 'F') tiles[y][x] = '.';
    }
    goal = { x: tx * TILE, y: ty * TILE, w: TILE, h: TILE };
  }
  tiles[ty][tx] = ch;
  levelRows[ty] = tiles[ty].join('');
}

/*** EXPORT/IMPORT ***/
export function doExport() {
  const s = levelRows.join('\n');
  const b = document.getElementById('exportBtn');
  if (navigator.clipboard?.writeText) {
    navigator.clipboard.writeText(s).then(() => flash(b, 'Copied!'));
  } else alert(s);
}

export function doImport() {
  const s = prompt('Paste ASCII level');
  if (!s) return;
  const rows = s.replace(/\r/g, '').split('\n');
  const m = rows.reduce((a, r) => Math.max(a, r.length), 0);
  levelRows = rows.map(r => (r + '.'.repeat(m - r.length)).slice(0, m));
  rebuildFromRows(); teleportToSpawn();
}

function flash(btn, msg) {
  const o = btn.textContent; btn.textContent = msg;
  setTimeout(() => btn.textContent = o, 800);
}

export function updateEnemies(tiles) {
  if (editMode) return;
  for (const e of enemies) {
    if (!e.dir) e.dir = 1;
    e.w = TILE;
    e.h = TILE;

    // gravity
    e.vy += 0.4;
    e.y += e.vy;

    // land on ground
    const gx = Math.floor(e.x / TILE);
    const gy = Math.floor((e.y + e.h - 1) / TILE);
    if (tiles[gy]?.[gx] === '#' || tiles[gy]?.[gx] === '-') {
      e.y = gy * TILE - e.h; // snap on top of block
      e.vy = 0;
    }

    // horizontal walk
    if (!e.vx) e.vx = 1.2;
    e.x += e.vx * (e.dir || 1);

    // turn around if wall ahead or no tile to stand on ahead (safer version)
    const faceX = Math.floor((e.x + e.dir * e.w) / TILE);
    const faceY = Math.floor((e.y + e.h / 2) / TILE);
    const footX = Math.floor((e.x + e.dir * e.w) / TILE);
    const footY = Math.floor((e.y + e.h) / TILE);
    const hitWall = tiles[faceY]?.[faceX] === '#' || tiles[faceY]?.[faceX] === '-';
    const noFloorAhead = !(tiles[footY]?.[footX] === '#' || tiles[footY]?.[footX] === '-');
    if (hitWall || noFloorAhead) {
      e.dir *= -1;
    }
  }
}

export function checkPlayerEnemyCollision() {
  for (let i = collectibles.length - 1; i >= 0; i--) {
    const c = collectibles[i];
    const hit = !(player.x + player.w < c.x ||
                  player.x > c.x + c.w ||
                  player.y + player.h < c.y ||
                  player.y > c.y + c.h);
    if (hit) collectibles.splice(i,1);
  }
  for (const e of enemies) {
    // axis aligned bounding box collision
    const hit = !(player.x + player.w < e.x ||
                  player.x > e.x + ENEMY_SIZE ||
                  player.y + player.h < e.y ||
                  player.y > e.y + ENEMY_SIZE);
    if (hit) {
      // stomp from above
      if (player.vy > 0 && player.y + player.h - e.y < 20) {
        e.remove = true;
        player.vy = -10;
      } else {
        // damage player / reset
        reset();
      }
    }
  }
  // remove stomped enemies
  for (let i = enemies.length - 1; i >= 0; i--) {
    if (enemies[i].remove) enemies.splice(i, 1);
  }
}